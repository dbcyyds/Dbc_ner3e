	[[nodiscard]] inline const Rec* Find(int Id)
	{
		for (const Rec& R : kTable)
		{
			if (R.Id == Id)
				return &R;
		}
		return nullptr;
	}

	// 0 或未收录返回空，调用方显示「未知」或数字。
	[[nodiscard]] inline const char* Name(int Id)
	{
		if (Id <= 0)
			return "未知";
		if (const Rec* R = Find(Id))
			return R->Zh;
		return nullptr;
	}

	[[nodiscard]] inline int CampOf(int Id)
	{
		if (const Rec* R = Find(Id))
			return R->Camp;
		return 0;
	}
